/* 设置窗口专用 preload —— 只暴露配置与数据管理接口
 * 与桌宠窗口的 preload.js 刻意分开：
 *   这里没有 speak / asr / chat / saveAudio / quit / setMouseThrough
 * 主进程侧还会用 sender 校验，确保这些接口只能被设置窗口调用
 */
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('cfg', {
  get: () => ipcRenderer.invoke('cfg:get'),
  set: (patch) => ipcRenderer.invoke('cfg:set', patch),
  setKey: (key) => ipcRenderer.invoke('cfg:set-key', key),
  setProvider: (payload) => ipcRenderer.invoke('cfg:set-provider', payload),
  testLLM: () => ipcRenderer.invoke('cfg:test-llm'),
  previewVoice: (text) => ipcRenderer.invoke('cfg:preview-voice', text),
  voices: () => ipcRenderer.invoke('cfg:voices'),
  models: () => ipcRenderer.invoke('cfg:models'),
  petSize: () => ipcRenderer.invoke('cfg:pet-size'),
  setPetSize: (payload) => ipcRenderer.invoke('cfg:set-pet-size', payload),
  shortcuts: () => ipcRenderer.invoke('cfg:shortcuts'),
  setShortcut: (payload) => ipcRenderer.invoke('cfg:set-shortcut', payload),
  resetShortcuts: (scope) => ipcRenderer.invoke('cfg:reset-shortcuts', scope),
  setShortcutsEnabled: (on) => ipcRenderer.invoke('cfg:set-shortcuts-enabled', on),
  setAutoStop: (sec) => ipcRenderer.invoke('cfg:set-auto-stop', sec),
  setModel: (payload) => ipcRenderer.invoke('cfg:set-model', payload),
  setVoice: (name) => ipcRenderer.invoke('cfg:set-voice', name),
  ttsEngine: () => ipcRenderer.invoke('cfg:tts-engine'),
  ttsEngineStatus: () => ipcRenderer.invoke('cfg:tts-engine-status'),
  setTtsEngine: (engine) => ipcRenderer.invoke('cfg:set-tts-engine', engine),
  cancelTtsSwitch: () => ipcRenderer.invoke('cfg:cancel-tts-switch'),
  bertStatus: () => ipcRenderer.invoke('cfg:bert-status'),
  ollamaModels: () => ipcRenderer.invoke('cfg:ollama-models'),
  pickEnginePath: (engine) => ipcRenderer.invoke('cfg:pick-engine-path', engine),
  setAsrLog: (on) => ipcRenderer.invoke('cfg:asr-log', on),
  asrOptions: () => ipcRenderer.invoke('cfg:asr-options'),
  getAutostart: () => ipcRenderer.invoke('cfg:get-autostart'),
  setAutostart: (on) => ipcRenderer.invoke('cfg:set-autostart', on),
  setAsr: (payload) => ipcRenderer.invoke('cfg:set-asr', payload),
  // GPU 加速版（Windows CUDA）：状态 / 下载 / 取消 / 卸载 / 切换
  asrEngine: () => ipcRenderer.invoke('cfg:asr-engine'),
  asrEngineInstall: (id) => ipcRenderer.invoke('cfg:asr-engine-install', id),
  asrEngineCancel: () => ipcRenderer.invoke('cfg:asr-engine-cancel'),
  asrEngineRemove: (id) => ipcRenderer.invoke('cfg:asr-engine-remove', id),
  asrEngineSwitch: (id) => ipcRenderer.invoke('cfg:asr-engine-switch', id),
  onAsrEngineProgress: (cb) => ipcRenderer.on('cfg:asr-engine-progress', (_e, p) => cb(p)),
  onChanged: (cb) => ipcRenderer.on('cfg:changed', (_e, cfg) => cb(cfg)),
  // 数据管理
  altsList: () => ipcRenderer.invoke('cfg:alts-list'),
  altsRemove: (payload) => ipcRenderer.invoke('cfg:alts-remove', payload),
  altsSet: (payload) => ipcRenderer.invoke('cfg:alts-set', payload),
  memoryGet: () => ipcRenderer.invoke('cfg:memory-get'),
  memoryPatch: (patch) => ipcRenderer.invoke('cfg:memory-patch', patch),
  memoryClear: () => ipcRenderer.invoke('cfg:memory-clear'),
  assetStatus: () => ipcRenderer.invoke('cfg:asset-status'),
  previewAsset: (payload) => ipcRenderer.invoke('cfg:preview-asset', payload),
  installAsset: (payload) => ipcRenderer.invoke('cfg:install-asset', payload),
  filePath: (file) => webUtils.getPathForFile(file),
  openPath: (id) => ipcRenderer.invoke('cfg:open-path', id),
  openResource: (id) => ipcRenderer.invoke('cfg:open-resource', id),
  dataInfo: () => ipcRenderer.invoke('cfg:data-info'),
  dataExport: () => ipcRenderer.invoke('cfg:data-export'),
  dataImport: () => ipcRenderer.invoke('cfg:data-import'),
  dataReset: (scope = 'all') => ipcRenderer.invoke('cfg:data-reset', scope),
  dataRestore: (file) => ipcRenderer.invoke('cfg:data-restore', file),
  close: () => ipcRenderer.send('cfg:close'),
  restartApp: () => ipcRenderer.invoke('cfg:restart'),
});
